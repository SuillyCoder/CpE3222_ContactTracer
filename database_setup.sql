-- Create and select the database
CREATE DATABASE IF NOT EXISTS cpe_contact_tracing
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE cpe_contact_tracing;

-- -------------------------------------------------------------
-- Table: users
-- Stores all registered individuals (students, faculty, guests)
-- user_id is a surrogate PK; usc_id_number is nullable so that
-- guests/visitors without a USC ID can still be registered.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id         INT             NOT NULL AUTO_INCREMENT,
    usc_id_number   VARCHAR(20)     NULL,           -- NULL for non-USC visitors
    user_type       ENUM(
                        'student',
                        'faculty',
                        'staff',
                        'guest'
                    )               NOT NULL,
    first_name      VARCHAR(50)     NOT NULL,
    middle_name     VARCHAR(50)     NULL,
    last_name       VARCHAR(50)     NOT NULL,
    barangay        VARCHAR(100)    NOT NULL,
    city            VARCHAR(100)    NOT NULL,
    province        VARCHAR(100)    NOT NULL,
    contact_number  VARCHAR(20)     NOT NULL,
    email           VARCHAR(100)    NOT NULL,
    date_registered DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id),
    UNIQUE KEY uq_usc_id (usc_id_number)   -- ensures no duplicate USC IDs
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Table: visit_logs
-- One row per entry event; time_out is filled on sign-out.
-- status reflects the current state of that visit row.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS visit_logs (
    visit_id    INT                     NOT NULL AUTO_INCREMENT,
    user_id     INT                     NOT NULL,
    time_in     DATETIME                NOT NULL DEFAULT CURRENT_TIMESTAMP,
    time_out    DATETIME                NULL,       -- NULL until the user signs out
    status      ENUM('IN', 'OUT')       NOT NULL DEFAULT 'IN',

    PRIMARY KEY (visit_id),
    CONSTRAINT fk_visit_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Table: admins
-- Standalone table – no FK link to users.
-- Password must be stored as a bcrypt / Argon2 hash in the app
-- layer before inserting; the VARCHAR(255) accommodates that.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admins (
    admin_id    INT             NOT NULL AUTO_INCREMENT,
    usc_id_number   VARCHAR(20)     NULL,           -- NULL for non-USC visitors
    username    VARCHAR(50)     NOT NULL,
    password    VARCHAR(255)    NOT NULL,   -- store HASHED value only

    PRIMARY KEY (admin_id),
    UNIQUE KEY uq_admin_username (username)
) ENGINE=InnoDB;

