-- -------------------------------------------------------------
-- Indexes for the admin search features
-- Covers: city, barangay, province, usc_id_number,
--         last_name / first_name, and time_in range queries
-- -------------------------------------------------------------
CREATE INDEX idx_users_city         ON users (city);
CREATE INDEX idx_users_barangay     ON users (barangay);
CREATE INDEX idx_users_province     ON users (province);
CREATE INDEX idx_users_usc_id       ON users (usc_id_number);
CREATE INDEX idx_users_last_name    ON users (last_name);
CREATE INDEX idx_users_first_name   ON users (first_name);
CREATE INDEX idx_visit_logs_time_in ON visit_logs (time_in);

